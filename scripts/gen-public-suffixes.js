#!/usr/bin/env node
// Writes server/data/public-suffixes.txt, the compact copy of the Public
// Suffix List that site-identity.js reads, from a copy of the list itself.
//
// Usage:
//   node scripts/gen-public-suffixes.js <public_suffix_list.dat>
//
// To update: download https://publicsuffix.org/list/public_suffix_list.dat
// (the list asks to be fetched from there and nowhere else), run this script
// on it, run the tests, and add a CHANGELOG line with the list's VERSION.
// A changed list can change what the checks report, so the rule set version
// goes up too.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { domainToASCII, fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'server', 'data', 'public-suffixes.txt');

/**
 * One rule in ASCII, as host names arrive from `URL`: each label through
 * `domainToASCII`, a wildcard label and the `!` of an exception kept.
 * @param {string} rule
 * @returns {string}
 */
function asciiRule(rule) {
  const exception = rule.startsWith('!');
  // An ASCII label is kept as it is: `domainToASCII` reads a label of digits alone ("0" in 0.bg) as an IPv4 address.
  const labels = (exception ? rule.slice(1) : rule).split('.')
    .map((label) => (label === '*' || /^[a-z0-9-]+$/.test(label) ? label : domainToASCII(label)));
  if (labels.some((label) => label === '' || /[^a-z0-9*-]/.test(label))) throw new Error(`Rule "${rule}" has no usable ASCII form.`);
  return `${exception ? '!' : ''}${labels.join('.')}`;
}

/**
 * @param {string} text  The list as published.
 * @returns {string}  The compact file.
 */
export function compact(text) {
  const version = /^\/\/ VERSION: (\S+)$/m.exec(text)?.[1];
  const commit = /^\/\/ COMMIT: (\S+)$/m.exec(text)?.[1];
  if (!version || !commit) throw new Error('No VERSION or COMMIT line: is this public_suffix_list.dat?');
  if (!text.includes('===BEGIN ICANN DOMAINS===') || !text.includes('===BEGIN PRIVATE DOMAINS===')) {
    throw new Error('The ICANN or the private section is missing.');
  }
  /** @type {Map<string, string[]>} */
  const byTopLabel = new Map();
  let count = 0;
  for (const line of text.split('\n')) {
    // A rule is the first run of characters on a line; comments start with //.
    const rule = line.trim().split(/\s/, 1)[0];
    if (rule === '' || rule.startsWith('//')) continue;
    const ascii = asciiRule(rule);
    const labels = ascii.replace(/^!/, '').split('.');
    const top = /** @type {string} */ (labels.pop());
    const rest = `${ascii.startsWith('!') ? '!' : ''}${labels.join('.')}`;
    const list = byTopLabel.get(top) ?? [];
    if (!list.includes(rest)) list.push(rest);
    byTopLabel.set(top, list);
    count += 1;
  }
  return [
    '# Public suffixes for Seekwide (server/src/util/public-suffix.js), compacted from the Public Suffix List,',
    '# https://publicsuffix.org/list/public_suffix_list.dat, both its ICANN and its private section.',
    `# VERSION: ${version}`,
    `# COMMIT: ${commit}`,
    `# ${count} rules. One line per top-level label: the label, a colon, then the rules that end in it with that label`,
    '# left off, separated by commas. An empty rule is the top-level label itself, "*" a wildcard label and a leading',
    '# "!" an exception. Labels are in ASCII (Punycode), as host names arrive from URL.',
    '# Generated by scripts/gen-public-suffixes.js. Do not edit by hand.',
    '#',
    '# This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was',
    '# not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.',
    ...[...byTopLabel].map(([top, rules]) => `${top}:${rules.join(',')}`),
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = process.argv[2];
  if (!source) {
    console.error('Usage: node scripts/gen-public-suffixes.js <public_suffix_list.dat>');
    process.exit(2);
  }
  const output = compact(readFileSync(source, 'utf8'));
  writeFileSync(TARGET, output);
  console.log(`Wrote ${path.relative(ROOT, TARGET)} (${Buffer.byteLength(output)} bytes).`);
}
