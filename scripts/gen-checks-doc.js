#!/usr/bin/env node
// Writes docs/checks.md from the check definitions, so the public list of
// checks can never drift from the code.
//
// Usage:
//   node scripts/gen-checks-doc.js           write docs/checks.md
//   node scripts/gen-checks-doc.js --check   exit 1 when docs/checks.md is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { allChecks } from '../server/src/checks/registry.js';
import { RULES_VERSION } from '../server/src/config.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'docs', 'checks.md');

const MODULE_TITLES = { seo: 'SEO', links: 'Links', security: 'Security', media: 'Media' };
const NEEDS_TEXT = {
  full_crawl: 'a complete crawl',
  sitemap: 'an XML sitemap',
  robots: 'a readable robots.txt',
  outbound: 'external link checks',
  lab_data: 'lab data from PageSpeed Insights',
  field_data: 'field data from the Chrome UX Report (needs a Google API key)',
  live_site: 'the deployed site (not a server on this machine)',
  image_files: 'the check of image files (requests to the image hosts)',
};

/** @param {string} value */
const cell = (value) => value.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\s+/g, ' ').trim();

function render() {
  const checks = allChecks();
  const lines = [
    '# Checks',
    '',
    `Rule set ${RULES_VERSION}. ${checks.length} scripted checks. This file is generated by \`scripts/gen-checks-doc.js\`; edit the check definitions, not this file.`,
    '',
    'Every check here is measured by code, so the same data always gets the same result. Some of that data is fetched or measured at audit time and can differ between two audits of an unchanged site: the answers of external sites, and the Core Web Vitals (a new lab test each time, and real-user data from a 28-day window that moves every day).',
    '',
    '- **Severity** orders the fixes. **Info** checks are rules of thumb: they are reported but never change a score.',
    '- **Confidence** is `confirmed` for a measured fact and `likely` for a strong signal that can have a legitimate exception.',
    '- **Needs** lists what the audit must provide: something from the crawl, the external link check, the check of image files, or the Core Web Vitals measurement by Google. A check that cannot run is reported as skipped, with the reason, and lowers the coverage figure instead of the score.',
    '',
  ];

  for (const moduleName of Object.keys(MODULE_TITLES)) {
    const group = checks.filter((check) => check.module === moduleName);
    if (group.length === 0) continue;
    lines.push(`## ${MODULE_TITLES[/** @type {keyof typeof MODULE_TITLES} */ (moduleName)]} (${group.length})`, '');
    lines.push('| Check | Severity | Confidence | What it looks at | How to fix | Needs | Reference |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const check of group) {
      const needs = check.requires.map((key) => NEEDS_TEXT[/** @type {keyof typeof NEEDS_TEXT} */ (key)] ?? key).join(', ') || '—';
      lines.push(
        `| **${cell(check.title)}**<br>\`${check.id}\` | ${check.severity} | ${check.confidence} | ${cell(check.description)} | ${cell(check.recommendation)} | ${needs} | [doc](${check.doc_ref}) (checked ${check.last_verified}) |`,
      );
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const output = render();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== output) {
    process.stderr.write('docs/checks.md is out of date. Run: node scripts/gen-checks-doc.js\n');
    process.exit(1);
  }
  process.stdout.write('docs/checks.md is up to date\n');
} else {
  writeFileSync(TARGET, output);
  process.stdout.write(`Wrote ${path.relative(ROOT, TARGET)}\n`);
}
