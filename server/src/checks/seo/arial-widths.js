/** @type {Map<number, number>} */
const WIDTHS = new Map();
for (const [start, widths] of RUNS) {
  widths.split(' ').forEach((width, offset) => WIDTHS.set(start + offset, Number(width)));
}

/** East Asian wide and full-width ranges, plus the common emoji blocks. */
const FULL_WIDTH_RANGES = [
  [0x1100, 0x115f], [0x2e80, 0x303e], [0x3041, 0x33ff], [0x3400, 0x4dbf], [0x4e00, 0x9fff],
  [0xa000, 0xa4cf], [0xac00, 0xd7a3], [0xf900, 0xfaff], [0xfe30, 0xfe4f], [0xff00, 0xff60],
  [0xffe0, 0xffe6], [0x1f300, 0x1f64f], [0x1f680, 0x1f6ff], [0x1f900, 0x1f9ff], [0x20000, 0x3fffd],
];

/**
 * @param {number} codePoint
 * @returns {boolean}
 */
function isFullWidth(codePoint) {
  return FULL_WIDTH_RANGES.some(([low, high]) => codePoint >= low && codePoint <= high);
}

/**
 * Estimated rendered width of `text` in Arial at `fontSizePx`, in pixels, not
 * rounded. The text is measured in NFC form. Characters missing from the table
 * count as 1139 units, CJK and other full-width characters as 2048 units.
 * @param {string} text
 * @param {number} fontSizePx
 * @returns {number}
 */
export function arialWidthPx(text, fontSizePx) {
  let units = 0;
  for (const char of text.normalize('NFC')) {
    const codePoint = /** @type {number} */ (char.codePointAt(0));
    units += WIDTHS.get(codePoint) ?? (isFullWidth(codePoint) ? FULL_WIDTH_UNITS : DEFAULT_UNITS);
  }
  return (units * fontSizePx) / UNITS_PER_EM;
}
